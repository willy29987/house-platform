/** 去除重複站名並保留順序 */
function uniqueStations(names: readonly string[]): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const name of names) {
    if (!seen.has(name)) {
      seen.add(name);
      out.push(name);
    }
  }
  return out;
}

export function getMrtStationsForLine(line: string): string[] {
  if (!line || line === "其他") return [];
  const stations = MRT_STATIONS_BY_LINE[line];
  return stations ? uniqueStations(stations) : [];
}

/** 表單下拉用：含既有自填站名（舊資料相容） */
export function getMrtStationOptions(line: string, currentStation: string): string[] {
  const stations = getMrtStationsForLine(line);
  const trimmed = currentStation.trim();
  if (trimmed && !stations.includes(trimmed)) {
    return [...stations, trimmed];
  }
  return stations;
}
